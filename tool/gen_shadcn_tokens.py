#!/usr/bin/env python3
"""Generates lib/model/shadcn_tokens.dart from the shadcn/ui themes.

Source: tool/shadcn/themes.ts (github.com/shadcn-ui/ui,
apps/v4/registry/themes.ts, MIT). It contains:
  - 7 base colors (neutral, stone, zinc, mauve, olive, mist, taupe): all
    tokens, light and dark;
  - 17 accent themes (blue, rose, ...): they override only some tokens
    (primary, secondary, chart, sidebar) on top of the base color.

oklch(L C H [/ A%]) colors become sRGB as in browsers on sRGB screens
(channel clipping), rounded like Dart.

Usage: python3 -I tool/gen_shadcn_tokens.py
"""

import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tool" / "shadcn" / "themes.ts"
OUT = ROOT / "lib" / "model" / "shadcn_tokens.dart"

BASE_COLORS = ["neutral", "stone", "zinc", "mauve", "olive", "mist", "taupe"]


def linear_to_srgb(c):
    c = max(0.0, min(1.0, c))
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def oklch_to_argb(L, C, H, alpha):
    a, b = C * math.cos(math.radians(H)), C * math.sin(math.radians(H))
    l_ = L + 0.3963377774 * a + 0.2158037573 * b
    m_ = L - 0.1055613458 * a - 0.0638541728 * b
    s_ = L - 0.0894841775 * a - 1.2914855480 * b
    l, m, s = l_ ** 3, m_ ** 3, s_ ** 3
    r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    bb = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
    ch = [int(linear_to_srgb(x) * 255 + 0.5) for x in (r, g, bb)]
    al = int(max(0, min(1, alpha)) * 255 + 0.5)
    return f"0x{al:02X}{ch[0]:02X}{ch[1]:02X}{ch[2]:02X}"


def parse_color(v):
    m = re.fullmatch(
        r"oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*(?:/\s*([\d.]+)(%?))?\s*\)",
        v.strip(),
    )
    if not m:
        return None
    alpha = 1.0
    if m.group(4) is not None:
        alpha = float(m.group(4)) / (100 if m.group(5) else 1)
    return oklch_to_argb(float(m.group(1)), float(m.group(2)), float(m.group(3)), alpha)


def block(src, start):
    """Content between the brace opening at `start` and the one closing it."""
    i = src.index("{", start)
    depth, k = 0, i
    while True:
        if src[k] == "{":
            depth += 1
        elif src[k] == "}":
            depth -= 1
            if depth == 0:
                return src[i + 1:k]
        k += 1


def vars_of(body):
    out = {}
    for m in re.finditer(r'"?([a-z0-9-]+)"?\s*:\s*"([^"]+)"', body):
        c = parse_color(m.group(2))
        if c:
            out[m.group(1)] = c
    return out


def main():
    src = SRC.read_text()
    themes = {}
    for m in re.finditer(r'name:\s*"([a-z]+)"', src):
        name = m.group(1)
        css = block(src, src.index("cssVars", m.end()))
        light = vars_of(block(css, css.index("light")))
        dark = vars_of(block(css, css.index("dark")))
        themes[name] = (light, dark)

    missing = [b for b in BASE_COLORS if b not in themes]
    if missing:
        sys.exit(f"Missing base colors: {missing}")

    def emit(name, light, dark):
        keys = [k for k in light if k in dark]
        lines = [f"  '{name}': {{"]
        for k in keys:
            lines.append(f"    '{k}': BoardToken(Color({light[k]}), Color({dark[k]})),")
        lines.append("  },")
        return lines

    out = [
        "// GENERATED by tool/gen_shadcn_tokens.py: do not edit by hand.",
        "//",
        "// shadcn/ui themes (https://github.com/shadcn-ui/ui, MIT). See",
        "// tool/shadcn/ for source and license.",
        "",
        "import 'dart:ui' show Color;",
        "",
        "import 'boardui_tokens.dart' show BoardToken;",
        "",
        "/// Base colors: all tokens (backgrounds, text, borders, primary...).",
        "const shadcnBaseColors = <String, Map<String, BoardToken>>{",
    ]
    for b in BASE_COLORS:
        out += emit(b, *themes[b])
    out.append("};")
    out.append("")
    out.append("/// Accent themes: override some of the base color's tokens.")
    out.append("const shadcnAccents = <String, Map<String, BoardToken>>{")
    accents = [n for n in themes if n not in BASE_COLORS]
    for a in accents:
        out += emit(a, *themes[a])
    out.append("};")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{len(BASE_COLORS)} base colors, {len(accents)} accents -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
