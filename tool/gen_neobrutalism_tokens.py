#!/usr/bin/env python3
"""Generates lib/model/neobrutalism_tokens.dart from the RetroUI palettes.

Source: tool/neobrutalism/global.css (github.com/neobrutalism/neobrutalism,
MIT). Each palette has light and dark values, resolved like the CSS cascade:
  light: :root  <- .theme-X
  dark:  :root  <- .dark <- .theme-X <- .dark .theme-X

Usage: python3 -I tool/gen_neobrutalism_tokens.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "tool" / "neobrutalism" / "global.css"
OUT = ROOT / "lib" / "model" / "neobrutalism_tokens.dart"

# Color tokens used by the RetroUI components.
TOKENS = [
    "background", "foreground", "card", "card-foreground", "popover",
    "primary", "primary-hover", "primary-foreground", "secondary",
    "secondary-foreground", "muted", "muted-foreground", "accent",
    "accent-foreground", "destructive", "destructive-foreground", "border",
    "input",
]


def blocks(css):
    """{selector: {variable: value}} for the top-level blocks."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    out = {}
    for m in re.finditer(r"([^{}]+)\{([^{}]*)\}", css):
        sel = " ".join(m.group(1).split())
        decls = dict(re.findall(r"--([a-z0-9-]+)\s*:\s*([^;]+);", m.group(2)))
        if decls:
            out.setdefault(sel, {}).update({k: v.strip() for k, v in decls.items()})
    return out


def argb(hex_value):
    h = hex_value.strip().lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    if len(h) == 6:
        h = "FF" + h
    elif len(h) == 8:
        h = h[6:8] + h[0:6]
    else:
        sys.exit(f"Unsupported color: {hex_value}")
    return "0x" + h.upper()


def main():
    b = blocks(SRC.read_text())
    root, dark = b[":root"], b[".dark"]
    palettes = {"yellow": ({}, {})}
    for sel in b:
        m = re.fullmatch(r"\.theme-([a-z]+)", sel)
        if m:
            palettes[m.group(1)] = (b[sel], b.get(f".dark .theme-{m.group(1)}", {}))

    lines = [
        "// GENERATED by tool/gen_neobrutalism_tokens.py: do not edit by hand.",
        "//",
        "// RetroUI / neobrutalism.com palettes (MIT). See tool/neobrutalism/.",
        "",
        "import 'boardui_tokens.dart' show BoardToken;",
        "",
        "/// Palette → token → light and dark values (same class as the BoardUI tokens).",
        "const neoPalettes = <String, Map<String, BoardToken>>{",
    ]
    for name, (light_over, dark_over) in palettes.items():
        light = {**root, **light_over}
        dark_vals = {**root, **dark, **light_over, **dark_over}
        lines.append(f"  '{name}': {{")
        for t in TOKENS:
            if t not in light or t not in dark_vals:
                sys.exit(f"Token mancante: {t} in {name}")
            lines.append(
                f"    '{t}': BoardToken(Color({argb(light[t])}), Color({argb(dark_vals[t])})),"
            )
        lines.append("  },")
    lines.append("};")
    OUT.write_text("\n".join(lines).replace(
        "import 'boardui_tokens.dart' show BoardToken;",
        "import 'dart:ui' show Color;\n\nimport 'boardui_tokens.dart' show BoardToken;") + "\n")
    print(f"{len(palettes)} palette x {len(TOKENS)} token -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
