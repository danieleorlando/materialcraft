#!/bin/sh
# Regenerates lib/export/button_skin_source.dart from
# packages/materialcraft/lib/src/*.dart.
# The "exported sources are aligned with the runtime" test fails if you forget to run it.
set -e
cd "$(dirname "$0")/.."
strip() {
  grep -v "^import 'package:flutter/material.dart';" "$1" | sed '1{/^$/d;}'
}
{
  echo '// GENERATED by tool/gen_skin_source.sh: do not edit by hand.'
  echo '// Sources of packages/materialcraft/lib/src/ (without imports), included in the exported code.'
  echo ''
  echo "const buttonSkinSource = r'''"
  strip packages/materialcraft/lib/src/button_skin.dart
  echo "''';"
  echo ''
  echo "const appButtonStylesSource = r'''"
  strip packages/materialcraft/lib/src/app_button_styles.dart
  echo "''';"
  echo ''
  echo "const sliderShapesSource = r'''"
  strip packages/materialcraft/lib/src/slider_shapes.dart
  echo "''';"
  echo ''
  echo "const appSwitchSource = r'''"
  strip packages/materialcraft/lib/src/app_switch.dart
  echo "''';"
  echo ''
  echo "const hardShadowBorderSource = r'''"
  strip packages/materialcraft/lib/src/hard_shadow_border.dart
  echo "''';"
} > lib/export/button_skin_source.dart
