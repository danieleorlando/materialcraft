/// [ColorScheme] roles selectable as a component's color.
///
/// Using a role instead of a fixed color makes the theme work
/// automatically in both light and dark mode.
enum SchemeRole {
  primary('Primary'),
  onPrimary('On primary'),
  primaryContainer('Primary container'),
  onPrimaryContainer('On primary container'),
  secondary('Secondary'),
  onSecondary('On secondary'),
  secondaryContainer('Secondary container'),
  onSecondaryContainer('On secondary container'),
  tertiary('Tertiary'),
  onTertiary('On tertiary'),
  tertiaryContainer('Tertiary container'),
  onTertiaryContainer('On tertiary container'),
  error('Error'),
  onError('On error'),
  errorContainer('Error container'),
  onErrorContainer('On error container'),
  surface('Surface'),
  onSurface('On surface'),
  onSurfaceVariant('On surface variant'),
  surfaceContainerLowest('Surface container lowest'),
  surfaceContainerLow('Surface container low'),
  surfaceContainer('Surface container'),
  surfaceContainerHigh('Surface container high'),
  surfaceContainerHighest('Surface container highest'),
  outline('Outline'),
  outlineVariant('Outline variant'),
  inverseSurface('Inverse surface'),
  onInverseSurface('On inverse surface'),
  inversePrimary('Inverse primary');

  const SchemeRole(this.label);

  final String label;

  Color resolve(ColorScheme s) => switch (this) {
    primary => s.primary,
    onPrimary => s.onPrimary,
    primaryContainer => s.primaryContainer,
    onPrimaryContainer => s.onPrimaryContainer,
    secondary => s.secondary,
    onSecondary => s.onSecondary,
    secondaryContainer => s.secondaryContainer,
    onSecondaryContainer => s.onSecondaryContainer,
    tertiary => s.tertiary,
    onTertiary => s.onTertiary,
    tertiaryContainer => s.tertiaryContainer,
    onTertiaryContainer => s.onTertiaryContainer,
    error => s.error,
    onError => s.onError,
    errorContainer => s.errorContainer,
    onErrorContainer => s.onErrorContainer,
    surface => s.surface,
    onSurface => s.onSurface,
    onSurfaceVariant => s.onSurfaceVariant,
    surfaceContainerLowest => s.surfaceContainerLowest,
    surfaceContainerLow => s.surfaceContainerLow,
    surfaceContainer => s.surfaceContainer,
    surfaceContainerHigh => s.surfaceContainerHigh,
    surfaceContainerHighest => s.surfaceContainerHighest,
    outline => s.outline,
    outlineVariant => s.outlineVariant,
    inverseSurface => s.inverseSurface,
    onInverseSurface => s.onInverseSurface,
    inversePrimary => s.inversePrimary,
  };

  /// Returns [s] with this role replaced by [c].
  ColorScheme override(ColorScheme s, Color c) => switch (this) {
    primary => s.copyWith(primary: c),
    onPrimary => s.copyWith(onPrimary: c),
    primaryContainer => s.copyWith(primaryContainer: c),
    onPrimaryContainer => s.copyWith(onPrimaryContainer: c),
    secondary => s.copyWith(secondary: c),
    onSecondary => s.copyWith(onSecondary: c),
    secondaryContainer => s.copyWith(secondaryContainer: c),
    onSecondaryContainer => s.copyWith(onSecondaryContainer: c),
    tertiary => s.copyWith(tertiary: c),
    onTertiary => s.copyWith(onTertiary: c),
    tertiaryContainer => s.copyWith(tertiaryContainer: c),
    onTertiaryContainer => s.copyWith(onTertiaryContainer: c),
    error => s.copyWith(error: c),
    onError => s.copyWith(onError: c),
    errorContainer => s.copyWith(errorContainer: c),
    onErrorContainer => s.copyWith(onErrorContainer: c),
    surface => s.copyWith(surface: c),
    onSurface => s.copyWith(onSurface: c),
    onSurfaceVariant => s.copyWith(onSurfaceVariant: c),
    surfaceContainerLowest => s.copyWith(surfaceContainerLowest: c),
    surfaceContainerLow => s.copyWith(surfaceContainerLow: c),
    surfaceContainer => s.copyWith(surfaceContainer: c),
    surfaceContainerHigh => s.copyWith(surfaceContainerHigh: c),
    surfaceContainerHighest => s.copyWith(surfaceContainerHighest: c),
    outline => s.copyWith(outline: c),
    outlineVariant => s.copyWith(outlineVariant: c),
    inverseSurface => s.copyWith(inverseSurface: c),
    onInverseSurface => s.copyWith(onInverseSurface: c),
    inversePrimary => s.copyWith(inversePrimary: c),
  };
}

/// Reference to a color: a scheme role, a fixed color or a
/// light/dark pair.
///
/// The code generated by [toDart] assumes the variables `colorScheme`
/// and `isDark` are in scope (see the exporter).
sealed class ColorRef {
  const ColorRef();

  Color resolve(ColorScheme scheme);

  /// Equivalent Dart expression. [inConst]: it's already in a `const` context.
  String toDart({bool inConst = false});

  /// True if the Dart expression is a constant.
  bool get isConst;

  bool get usesIsDark => false;

  String get label;
}

class RoleColor extends ColorRef {
  const RoleColor(this.role, {this.alpha = 1});

  final SchemeRole role;

  /// Opacity applied to the role color (1 = full).
  final double alpha;

  @override
  Color resolve(ColorScheme scheme) {
    final c = role.resolve(scheme);
    return alpha >= 1 ? c : c.withValues(alpha: c.a * alpha);
  }

  @override
  String toDart({bool inConst = false}) => alpha >= 1
      ? 'colorScheme.${role.name}'
      : 'colorScheme.${role.name}.withValues(alpha: ${formatNum(alpha)})';

  @override
  bool get isConst => false;

  @override
  String get label =>
      alpha >= 1 ? role.label : '${role.label} · ${(alpha * 100).round()}%';

  @override
  bool operator ==(Object other) =>
      other is RoleColor && other.role == role && other.alpha == alpha;

  @override
  int get hashCode => Object.hash(role, alpha);
}

class CustomColor extends ColorRef {
  const CustomColor(this.color);

  final Color color;

  @override
  Color resolve(ColorScheme scheme) => color;

  @override
  String toDart({bool inConst = false}) =>
      '${inConst ? '' : 'const '}Color(0x${hexArgb(color)})';

  @override
  bool get isConst => true;

  @override
  String get label => colorLabel(color);

  @override
  bool operator ==(Object other) =>
      other is CustomColor && other.color.toARGB32() == color.toARGB32();

  @override
  int get hashCode => color.toARGB32().hashCode;
}

/// Color with different values in light and dark mode.
class AdaptiveColor extends ColorRef {
  const AdaptiveColor(this.light, this.dark);

  final Color light;
  final Color dark;

  @override
  Color resolve(ColorScheme scheme) =>
      scheme.brightness == Brightness.dark ? dark : light;

  @override
  String toDart({bool inConst = false}) =>
      '(isDark ? const Color(0x${hexArgb(dark)}) : const Color(0x${hexArgb(light)}))';

  @override
  bool get isConst => false;

  @override
  bool get usesIsDark => true;

  @override
  String get label => '${colorLabel(light)} / ${colorLabel(dark)}';

  @override
  bool operator ==(Object other) =>
      other is AdaptiveColor &&
      other.light.toARGB32() == light.toARGB32() &&
      other.dark.toARGB32() == dark.toARGB32();

  @override
  int get hashCode => Object.hash(light.toARGB32(), dark.toARGB32());
}

/// BoardUI semantic token (e.g. `text-primary`), with light and dark values.
class TokenColor extends ColorRef {
  const TokenColor(this.name, [this.set]);

  final String name;

  /// Recolored set (chosen accent / neutrals), `null` = official colors.
  final String? set;

  BoardToken get token {
    final t = boardTokensFor(set)?[name];
    if (t == null) throw ArgumentError('Unknown BoardUI token: $name');
    return t;
  }

  bool get _sameInBothModes => token.light.toARGB32() == token.dark.toARGB32();

  @override
  Color resolve(ColorScheme scheme) =>
      scheme.brightness == Brightness.dark ? token.dark : token.light;

  @override
  String toDart({bool inConst = false}) => _sameInBothModes
      ? '/* $name */ ${CustomColor(token.light).toDart(inConst: inConst)}'
      : '/* $name */ (isDark ? const Color(0x${hexArgb(token.dark)}) '
            ': const Color(0x${hexArgb(token.light)}))';

  @override
  bool get isConst => _sameInBothModes;

  @override
  bool get usesIsDark => !_sameInBothModes;

  @override
  String get label => set == null ? name : '$name · custom';

  @override
  bool operator ==(Object other) =>
      other is TokenColor && other.name == name && other.set == set;

  @override
  int get hashCode => Object.hash(name, set);
}

/// Token of a RetroUI / neobrutalism palette (e.g. yellow · primary).
class PaletteColor extends ColorRef {
  const PaletteColor(this.palette, this.name);

  final String palette;
  final String name;

  BoardToken get token {
    final t = neoPaletteTokens(palette)?[name];
    if (t == null) {
      throw ArgumentError('Unknown RetroUI token: $palette/$name');
    }
    return t;
  }

  bool get _sameInBothModes => token.light.toARGB32() == token.dark.toARGB32();

  String get _exportName =>
      isCustomNeoPalette(palette) ? 'custom.$name' : '$palette.$name';

  @override
  Color resolve(ColorScheme scheme) =>
      scheme.brightness == Brightness.dark ? token.dark : token.light;

  @override
  String toDart({bool inConst = false}) => _sameInBothModes
      ? '/* $_exportName */ ${CustomColor(token.light).toDart(inConst: inConst)}'
      : '/* $_exportName */ (isDark ? const Color(0x${hexArgb(token.dark)}) '
            ': const Color(0x${hexArgb(token.light)}))';

  @override
  bool get isConst => _sameInBothModes;

  @override
  bool get usesIsDark => !_sameInBothModes;

  @override
  String get label => isCustomNeoPalette(palette)
      ? 'Custom RetroUI · $name'
      : 'RetroUI $palette · $name';

  @override
  bool operator ==(Object other) =>
      other is PaletteColor && other.palette == palette && other.name == name;

  @override
  int get hashCode => Object.hash(palette, name);
}

/// shadcn/ui token (e.g. `primary`): base color (neutrals) plus an optional
/// accent, official or generated. [alpha] for colors like `ring/50`.
class ShadcnColor extends ColorRef {
  const ShadcnColor(this.base, this.accent, this.name, {this.alpha = 1});

  final String base;
  final String? accent;
  final String name;
  final double alpha;

  BoardToken get token {
    final t = shadcnToken(base, accent, name);
    if (t == null) throw ArgumentError('Unknown shadcn token: $name');
    return t;
  }

  Color _apply(Color c) => alpha == 1 ? c : c.withValues(alpha: c.a * alpha);
  Color get light => _apply(token.light);
  Color get dark => _apply(token.dark);

  bool get _sameInBothModes => light.toARGB32() == dark.toARGB32();

  String get _exportName =>
      '$name${alpha == 1 ? '' : '/${(alpha * 100).round()}'}';

  @override
  Color resolve(ColorScheme scheme) =>
      scheme.brightness == Brightness.dark ? dark : light;

  @override
  String toDart({bool inConst = false}) => _sameInBothModes
      ? '/* shadcn.$_exportName */ ${CustomColor(light).toDart(inConst: inConst)}'
      : '/* shadcn.$_exportName */ (isDark ? const Color(0x${hexArgb(dark)}) '
            ': const Color(0x${hexArgb(light)}))';

  @override
  bool get isConst => _sameInBothModes;

  @override
  bool get usesIsDark => !_sameInBothModes;

  @override
  String get label => 'shadcn · $_exportName';

  @override
  bool operator ==(Object other) =>
      other is ShadcnColor &&
      other.base == base &&
      other.accent == accent &&
      other.name == name &&
      other.alpha == alpha;

  @override
  int get hashCode => Object.hash(base, accent, name, alpha);
}

String hexArgb(Color c) =>
    c.toARGB32().toRadixString(16).padLeft(8, '0').toUpperCase();

/// "#RRGGBB" or "#RRGGBB · 60%" if the color is transparent.
String colorLabel(Color c) {
  if (c.a == 0) return 'transparent';
  final hex = '#${hexArgb(c).substring(2)}';
  final a = (c.a * 100).round();
  final named = tailwindName(c);
  final base = named ?? hex;
  return a >= 100 ? base : '$base · $a%';
}

/// Parses "#RRGGBB", "RRGGBB" or "AARRGGBB".
Color? parseHex(String input) {
  var s = input
      .trim()
      .replaceFirst('#', '')
      .replaceFirst(RegExp('^0x', caseSensitive: false), '');
  if (s.length == 6) s = 'FF$s';
  if (s.length != 8) return null;
  final v = int.tryParse(s, radix: 16);
  return v == null ? null : Color(v);
}

/// Formats a double as a compact Dart literal (12 instead of 12.0).
String formatNum(double v) {
  if (v == v.roundToDouble()) return v.toInt().toString();
  return v.toStringAsFixed(3).replaceFirst(RegExp(r'0+$'), '');
}

/// Tailwind CSS v4 palette with the BoardUI overrides (generated by
/// tool/gen_boardui_tokens.py). `accent` is an alias of `blue`.
const tailwindPalette = boardPrimitives;

/// Tailwind name ("blue-600") if the color (ignoring alpha) is in the palette.
String? tailwindName(Color c) {
  final rgb = c.toARGB32() & 0xFFFFFF;
  for (final fam in tailwindPalette.entries) {
    if (fam.key == 'accent') continue; // alias of blue
    for (final shade in fam.value.entries) {
      if (shade.value.toARGB32() & 0xFFFFFF == rgb) {
        return '${fam.key}-${shade.key}';
      }
    }
  }
  if (rgb == 0xFFFFFF) return 'white';
  if (rgb == 0x000000) return 'black';
  return null;
}
